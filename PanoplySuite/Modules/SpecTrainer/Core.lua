ST.trees = {}
ST.GRID_ROWS = 7     -- the rows a tree grid has at least (Classic Era's trees have 7; WoW Forever's go to 8: ST:Trees sets T.rows)

-- 0.9.9.4 hotfix (Nov 22 2026: "the talent trees in our menu system doesnt match the talen tree from blizzard"): WoW Forever's
-- talents are Blizzard's trait tree, and its trees are not Classic Era's. On WoW Forever the static trees come from Blizzard's own
-- client tables of build 1.60.1.71037 (Data/ForeverTalentData.lua, generated by tools/build_forever_talents.py from
-- tools/cache/forever-traits-71037/, as CSV from wago.tools); in the game the player's own class uses the game's tree (ST:LiveTree):
--   a tab is one of the class's three specs; a talent is a node: id = the node id, tier = row - 1, col = column - 1, ranks = its
--   max ranks; prereqs = the nodes with an arrow into it (any one of them opens it, at the rank ST:NeedRank says); gates = the
--   points it needs in a counted group of nodes (T.groups), not 5 a row. Classic Era keeps Data/TalentData.lua.
local function buildForever(d)
  local T = { tabs = {}, byId = {}, byName = {}, forever = true, tree = d.tree, prereq = d.prereq, groups = {}, rows = ST.GRID_ROWS, data = d }
  for i, name in ipairs(d.specs) do T.tabs[i] = { index = i, id = i, name = name, talents = {} } end
  local list = {}
  for id, n in pairs(d.nodes) do list[#list + 1] = { id = id, n = n } end
  table.sort(list, function(a, b)
    if a.n[4] ~= b.n[4] then return a.n[4] < b.n[4] end
    if a.n[5] ~= b.n[5] then return a.n[5] < b.n[5] end
    if a.n[6] ~= b.n[6] then return a.n[6] < b.n[6] end
    return a.id < b.id
  end)
  for _, x in ipairs(list) do
    local n, tab = x.n, T.tabs[x.n[4]]
    local tal = { id = x.id, entry = n[1], ranks = n[2], spell = n[3], tier = n[5] - 1, col = n[6] - 1, key = n[7], name = n[7],
                  icon = (n[8] or 0) ~= 0 and n[8] or nil, tab = n[4], letter = #tab.talents + 1, prereqs = {}, gates = d.gates[x.id] or {} }
    tab.talents[tal.letter] = tal
    T.byId[tal.id] = tal
    if not T.byName[tal.tab .. ":" .. tal.key] then T.byName[tal.tab .. ":" .. tal.key] = tal end
    if n[5] > T.rows then T.rows = n[5] end
  end
  for g, ids in pairs(d.groups) do T.groups[g] = ids end
  for _, e in ipairs(d.edges) do
    local to = T.byId[e[2]]
    if to and T.byId[e[1]] then to.prereqs[#to.prereqs + 1] = e[1] end
  end
  for _, tal in pairs(T.byId) do
    -- (Classic's single prerequisite fields, for the code that only draws or names one: the first arrow in)
    tal.prereq = tal.prereqs[1]
    tal.prereqRank = tal.prereq and ST:NeedRank(T, T.byId[tal.prereq]) or nil
  end
  return T
end
local function foreverTrees(classFile)
  local FD = Panoply.ForeverTalentData
  local d = FD and FD.classes and FD.classes[classFile]
  if not d then return nil end
  return buildForever(d)
end
