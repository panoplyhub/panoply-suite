-- Ready-made plans for a class: Panoply Suite basic (Specs.lua) plus the optional data file
-- PanoplySuite_SpecPlans (same shape, from the companion app later). Bad plans are left out with
-- one plain chat line.
function ST:ReadyMade(classFile)
  classFile = classFile or self:ClassFile()
  self.ready = self.ready or {}
  -- (kept per tree: a build is checked again when the tree in use changes, e.g. once the game's own tree has been read)
  self.readyTree = self.readyTree or {}
  if self.ready[classFile] and self.readyTree[classFile] == self.trees[classFile] then return self.ready[classFile] end
  local out = {}
  local S = Panoply.SpecBasic
  local T = self:Trees(classFile)
  -- WoW Forever (0.9.9.4 hotfix): the trees are WoW Forever's (Blizzard's tables, or the game's own), and the suggested builds are NOT PanoplyGuide's (Nov
  -- 22 2026: "dont use panoplyguides guides at all....use only the ones we grab online ... talent guides that is"). They come from
  -- Panoply.ForeverBuilds, the builds collected from public guide sites, which is not shipped yet: until it is, a WoW Forever class has no
  -- suggested build and the player plans by hand (ST:NoBuildLine). The Classic Era plans of Specs.lua are written for Classic's trees and
  -- are never offered there; its class-wide trainer lists (S.spells) still sort the trainer (ST:VerdictPlan).
  --   Panoply.ForeverBuilds = { classes = { [CLASS] = { { key, name, spec (1-3), default, source (the site, in plain words), url,
  --     points = { node ids, one per point from level 10 }, notes = { [level] = text } }, ... } } }
  local forever = T and T.forever
  if forever then
    local FB = Panoply.ForeverBuilds
    local list = type(FB) == "table" and type(FB.classes) == "table" and FB.classes[classFile] or nil
    self.droppedBuilds = self.droppedBuilds or {}
    local dropped = {}
    self.droppedBuilds[classFile] = dropped
    -- the tree in use, by spell and by name (a name two talents share is not used)
    local index = { spell = {}, name = {} }
    for id, tal in pairs(T.byId) do
      if tal.spell and tal.spell ~= 0 then index.spell[tal.spell] = (index.spell[tal.spell] == nil) and id or false end
      local k = tal.name:lower()
      index.name[k] = (index.name[k] == nil) and id or false
    end
    for _, b in ipairs(type(list) == "table" and list or {}) do
      -- a point is { talent name, rank, spell id } (Data/ForeverBuilds.lua) or a node id: found on the tree in use by its spell, else by
      -- its name (the same talent on the game's tree and on the static one), and each point must be the talent's next rank
      local pts, bad, count = {}, nil, {}
      local function node(x)
        if type(x) == "number" then return T.byId[x] and x or nil end
        if type(x) ~= "table" then return nil end
        local id = (x[3] or 0) ~= 0 and index.spell[x[3]] or nil
        if not id and type(x[1]) == "string" then id = index.name[x[1]:lower()] end
        return id or nil
      end
      if b.unresolved then
        bad = "the research has no name for some points (" .. tostring(b.unresolved) .. ")"
      elseif type(b.points) == "table" then
        for i, x in ipairs(b.points) do
          local id = node(x)
          if not id then bad = bad or ("%s is not in this tree"):format(type(x) == "table" and tostring(x[1]) or tostring(x)) break end
          count[id] = (count[id] or 0) + 1
          if type(x) == "table" and x[2] ~= count[id] then bad = bad or ("point %d: %s rank %d after %d"):format(i, tostring(x[1]), x[2], count[id] - 1) end
          pts[i] = id
        end
      elseif type(b.final) == "table" then
        -- the site gives only the level-60 layout: no order is invented for the player (the plan is marked noOrder); the points are laid
        -- in an order the rules allow only so the tree can be drawn and checked
        local want = {}
        for k, v in pairs(b.final) do
          local x, r = (type(v) == "table") and v or k, (type(v) == "table") and v[2] or v
          local id = node(x)
          if not id then bad = bad or ("%s is not in this tree"):format(type(x) == "table" and tostring(x[1]) or tostring(x)) break end
          want[id] = (want[id] or 0) + r
        end
        if not bad then pts, bad = self:LayoutOrder(classFile, want) end
      else
        bad = "no points"
      end
      if not bad then
        local ok, err = self:Check(classFile, pts)
        bad = (not ok and err) or (#pts ~= self.POINTS and ("%d points, not %d"):format(#pts, self.POINTS)) or nil
      end
      local name = b.name or (b.spec and T.tabs[b.spec] and T.tabs[b.spec].name) or tostring(b.key)
      if bad or type(b.key) ~= "string" then
        -- (expected while a site's tree and this one differ: kept for the tests and /panoply debug, never offered)
        dropped[#dropped + 1] = { key = b.key, name = name, why = tostring(bad or "it has no key") }
        Panoply:Debug("spec", "build left out", tostring(b.key), tostring(bad))
      else
        local why, levels = {}, {}
        for lv in pairs(type(b.notes) == "table" and b.notes or {}) do if type(lv) == "number" then levels[#levels + 1] = lv end end
        table.sort(levels)
        for _, lv in ipairs(levels) do
          local tal = T.byId[pts[lv - self.FIRST_LEVEL + 1] or 0]
          if tal and not why[tal.key] then why[tal.key] = b.notes[lv] end
        end
        -- the trainer spells this build leaves optional or skips (a shield spell for a two-hander build): those of Specs.lua's leveling
        -- plan with the same main tree. They are about the trainer's spells, not the talents.
        local main = self:TreeSummary(classFile, pts):match("^%d+ ([^,]+)")
        local spells, spellsFrom = { optional = {}, skip = {} }, nil
        for _, sd in ipairs(S and S.classes[classFile] or {}) do
          if not spellsFrom and not sd.at60 and type(sd.trees) == "string" and sd.trees:match("^%d+ ([^,]+)") == main and sd.spells then
            spells, spellsFrom = sd.spells, sd.key
          end
        end
        out[#out + 1] = { key = b.key, name = name, default = b.default and true or nil,
                          summary = b.source and ("Source: %s."):format(b.source) or nil, trees = self:TreeSummary(classFile, pts),
                          points = pts, spells = spells, spellsFrom = spellsFrom, why = why, notes = b.notes, classSpells = S and S.spells[classFile],
                          class = classFile, source = "public", sourceLine = b.source, link = b.url, spec = b.spec,
                          noOrder = b.points == nil or nil, updated = b.updated, distinct = b.distinct or nil,
                          -- (0.9.9.4 review: the data says some points were named by Panoply, not by the page: the card's tooltip says so)
                          inferred = (type(b.inferred) == "string" and b.inferred ~= "") and b.inferred or nil }
      end
    end
    -- 0.9.9.4 ("One per spec, extra only if different"): ONE build per spec, the one with a level by level order, else the newer
    -- page date, else the data's order; a build marked distinct (genuinely different: Paladin Protection's two, Enhancement's mana focus)
    -- shows as well. The others are folded into the one offered: it names their guides (alsoFrom), and they are listed in
    -- self.foldedBuilds[class] (never offered). Chosen among the builds that fit the tree in use.
    do
      local bySpec, order = {}, {}
      for i, p in ipairs(out) do
        p.order = i
        local sp = p.spec or 0
        if not bySpec[sp] then bySpec[sp] = {} order[#order + 1] = sp end
        table.insert(bySpec[sp], p)
      end
      local keep, folded = {}, {}
      self.foldedBuilds = self.foldedBuilds or {}
      self.foldedBuilds[classFile] = folded
      for _, sp in ipairs(order) do
        local list = bySpec[sp]
        local best
        for _, p in ipairs(list) do
          if not best then best = p
          else
            local po, bo = not p.noOrder, not best.noOrder
            if po ~= bo then if po then best = p end
            elseif (p.updated or "") > (best.updated or "") then best = p end
          end
        end
        for _, p in ipairs(list) do
          if p == best or p.distinct then keep[#keep + 1] = p
          else
            folded[#folded + 1] = { key = p.key, name = p.name, into = best.key, guide = (self:BuildGuide(p.sourceLine)) }
            best.alsoFrom = best.alsoFrom or {}
            table.insert(best.alsoFrom, (self:BuildGuide(p.sourceLine)) or p.sourceLine)
          end
        end
      end
      table.sort(keep, function(x, y) return x.order < y.order end)
      out = keep
    end
    -- the default (shown before a plan is picked): the first build with a level by level order, else the first
    local def
    for _, p in ipairs(out) do if p.default then def = p end end
    if not def then
      for _, p in ipairs(out) do if not p.noOrder and not def then def = p end end
      def = def or out[1]
      if def then def.default = true end
    end
  end
  for _, d in ipairs((not forever) and S and S.classes[classFile] or {}) do
    local pts, err = self:Expand(classFile, d.steps)
    if pts then
      out[#out + 1] = { key = d.key, name = d.name, role = d.role, summary = d.summary, trees = d.trees, default = d.default,
                        at60 = d.at60, points = pts, spells = d.spells, why = S.why[classFile], classSpells = S.spells[classFile],
                        class = classFile, source = "basic" }
    else
      Panoply:Debug("spec", d.key, err)
    end
  end
  local file = _G.PanoplySuite_SpecPlans
  if type(file) == "table" and type(file.plans) == "table" and type(file.plans[classFile]) == "table" then
    if (tonumber(file.version) or 0) > 1 then
      self:Notice("PanoplySuite_SpecPlans is newer than this Panoply Suite; its plans are left out.")
    else
      local keys = {}
      for k in pairs(file.plans[classFile]) do keys[#keys + 1] = k end
      table.sort(keys)
      for _, k in ipairs(keys) do
        local d = file.plans[classFile][k]
        local pts, why, spells = {}, {}, { optional = {}, skip = {} }
        local bad = type(d) ~= "table" or type(d.talents) ~= "table"
        if not bad then
          for i, t in ipairs(d.talents) do
            if type(t) ~= "table" or t[1] ~= self.FIRST_LEVEL + i - 1 then bad = true break end
            pts[i] = t[2]
          end
        end
        if not bad and not self:Check(classFile, pts) then bad = true end
        if bad then
          self:Notice(("The plan %q in PanoplySuite_SpecPlans breaks the talent rules; it is left out."):format(tostring(k)))
        else
          local T = self:Trees(classFile)
          for id, s in pairs(d.why or {}) do local tal = T.byId[id] if tal then why[tal.key] = s end end
          for sid, v in pairs(d.spells or {}) do
            local name = self:SpellNameById(classFile, sid)
            if name and type(v) == "table" then
              if v[1] == "skip" then spells.skip[name] = v[2] or "" elseif v[1] == "optional" then spells.optional[name] = v[2] or "" end
            end
          end
          out[#out + 1] = { key = k, name = d.name or k, role = d.role, summary = d.summary, trees = self:TreeSummary(classFile, pts),
                            points = pts, spells = spells, why = why, classSpells = S and S.spells[classFile], class = classFile,
                            source = file.source or "PanoplySuite_SpecPlans" }
        end
      end
    end
  end
  self.ready[classFile] = out
  self.readyTree[classFile] = self.trees[classFile]
  return out
end

function ST:Notice(msg)
  self.noticed = self.noticed or {}
  if self.noticed[msg] then return end
  self.noticed[msg] = true
  Panoply:Print(msg)
end

