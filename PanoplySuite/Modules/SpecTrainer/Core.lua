-- "31 Arms, 20 Fury"
function ST:TreeSummary(classFile, points, n)
  local T = self:Trees(classFile)
  local _, spent = self:RanksAt(classFile, points, n)
  local order = {}
  for i = 1, #T.tabs do if spent[i] > 0 then order[#order + 1] = i end end
  table.sort(order, function(a, b) return spent[a] > spent[b] end)
  local parts = {}
  for _, i in ipairs(order) do parts[#parts + 1] = spent[i] .. " " .. T.tabs[i].name end
  return #parts > 0 and table.concat(parts, ", ") or "No points yet"
end

-- 0.9.9.4 hotfix: a saved plan made for the old talent trees (Classic Era's, which older versions showed on WoW Forever too) names
-- talents that are not in WoW Forever's tree. It is never mapped onto the new tree and never followed: it stays in the saved data, out
-- of the plan list, and the Talents tab and one chat line ask the player to pick a build again.
-- 0.9.9.4 review: old means a talent id that is in neither Blizzard's static tree (Data/ForeverTalentData.lua) nor the tree in use (a
-- talent new to the game's own tree), so a talent the game's tree leaves out does not make a plan "old".
function ST:IsOldPlan(plan)
  if type(plan) ~= "table" or type(plan.points) ~= "table" then return false end
  local T = self:Trees(plan.class)
  if not (T and T.forever) then return false end
  local static = self:StaticTree(plan.class)
  for _, id in ipairs(plan.points) do
    if not ((static and static.byId[id]) or T.byId[id]) then return true end
  end
  return false
end

