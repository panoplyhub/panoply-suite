-- 0.9.9.4: the game's own tree. For the player's class on WoW Forever the tree is read from the game (C_Traits: the tree's nodes, each
-- node's max ranks, entry -> spell name and icon, the arrows it draws and where it is drawn) and laid on Blizzard's static tree
-- (Data/ForeverTalentData.lua, from the same game's tables), whose places, gates and arrows were settled by tools/build_forever_talents.py.
-- 0.9.9.4 review: the game's raw coordinates are not a clean grid (Warlock's Improved Life Tap at y 2120 and Amplify Curse at 3320 beside
-- the 2130 / 3330 rows, Hunter's Improved Serpent Sting at y 39300, dead copies of Hunter's Lightning Reflexes and Priest's Holy
-- Specialization far off it), so:
--   * a node the static tree has (by id, else by spell, else by name: a renumbered node) keeps the static tree's spec, row, column, gates
--     and arrows; the game gives only its ranks, name, spell and icon;
--   * a node the static tree does not have (genuinely new) is placed by the static builder's rules on the grid the known nodes draw: a
--     coordinate within SNAP of a grid line is that line; one exactly ten times a grid line is read at that line; anything else is off the
--     grid and left out, as is a copy of a talent already on the grid and a node on a square already taken. Its gates and groups are those
--     the static tree gives the nodes of the same spec and row (none when that row has no static node: no gate is guessed); its arrows the
--     game's.
-- UNVERIFIED on the live client: the exact shapes of these answers; when anything needed is missing the static tree is kept.
-------------------------------------------------------------------------------
ST.LIVE_SNAP = 20
function ST:LiveTree(classFile)
  local static = self:StaticTree(classFile)
  if not static then return nil, "no static tree to lay the game's nodes on" end
  local config = C.TalentConfig and C.TalentConfig()
  if not config then return nil, "no config" end
  local tree = (C.TalentConfigTree and C.TalentConfigTree(config)) or static.tree
  local ids = tree and C.TalentTreeNodes(tree)
  if type(ids) ~= "table" or #ids < 30 then return nil, "no tree nodes" end
  local nodes = {}
  for _, id in ipairs(ids) do
    local n = C.TalentNode(config, id)
    if n and n.visible and n.max > 0 then
      n.spell, n.name = C.TalentEntrySpell(config, n.entry)
      if n.name then nodes[#nodes + 1] = n end
    end
  end
  if #nodes < 30 then return nil, "too few nodes with a name" end
  table.sort(nodes, function(a, b) return a.id < b.id end)
  -- the static node each game node is: by id, else by spell and ranks, else by name and ranks (each static node once)
  local bySpell, byName = {}, {}
  local function index(t, k, sid) if t[k] == nil then t[k] = sid else t[k] = false end end   -- false: two static nodes share it
  for sid, st in pairs(static.byId) do
    if st.spell and st.spell ~= 0 then index(bySpell, st.spell .. "#" .. st.ranks, sid) end
    index(byName, st.name .. "#" .. st.ranks, sid)
  end
  local staticOf, used = {}, {}
  for _, n in ipairs(nodes) do if static.byId[n.id] then staticOf[n.id] = static.byId[n.id] used[n.id] = true end end
  for _, n in ipairs(nodes) do
    if not staticOf[n.id] then
      local sid = (n.spell and bySpell[n.spell .. "#" .. n.max]) or byName[n.name .. "#" .. n.max] or nil
      if sid and not used[sid] then staticOf[n.id] = static.byId[sid] used[sid] = true end
    end
  end
  -- the grid the known nodes draw: each row's y and each spec's columns' x (the most common), and the step between lines
  local function vote(t, k, v) t[k] = t[k] or {} t[k][v] = (t[k][v] or 0) + 1 end
  local function top(c) local best, bn for v, k in pairs(c) do if not bn or k > bn or (k == bn and v < best) then best, bn = v, k end end return best end
  local yv, xv = {}, { {}, {}, {} }
  for _, n in ipairs(nodes) do
    local st = staticOf[n.id]
    if st and n.posX and n.posY then vote(yv, st.tier + 1, n.posY) vote(xv[st.tab], st.col + 1, n.posX) end
  end
  local rowY, colX, steps = {}, { {}, {}, {} }, {}
  for r, c in pairs(yv) do rowY[r] = top(c) end
  for sp = 1, 3 do for col, c in pairs(xv[sp]) do colX[sp][col] = top(c) end end
  local function stepOf(lines)
    local diffs = {}
    for i, v in pairs(lines) do if lines[i + 1] then vote(diffs, 1, lines[i + 1] - v) end end
    return diffs[1] and top(diffs[1]) or nil
  end
  local stepY, stepX = stepOf(rowY), nil
  for sp = 1, 3 do local s = stepOf(colX[sp]) if s then steps[#steps + 1] = s end end
  if #steps > 0 then local c = {} for _, s in ipairs(steps) do c[s] = (c[s] or 0) + 1 end stepX = top(c) end
  -- a coordinate on lines { [index] = coordinate } with this step: the index it is read at (1 .. most), or nil (off the grid)
  local SNAP = self.LIVE_SNAP
  local function settle(v, lines, step, most)
    if not (v and step and step > 0) then return nil end
    local i0, v0
    for i, c in pairs(lines) do if not i0 or i < i0 then i0, v0 = i, c end end
    if not i0 then return nil end
    local function at(w, snap)
      local k = i0 + math.floor((w - v0) / step + 0.5)
      if k >= 1 and k <= most and math.abs(w - (v0 + (k - i0) * step)) <= snap then return k end
    end
    return at(v, SNAP) or (v % 10 == 0 and at(v / 10, 0)) or nil
  end
  local d = { tree = tree, prereq = "full", specs = {}, nodes = {}, gates = {}, groups = {}, edges = {} }
  for i = 1, 3 do d.specs[i] = static.tabs[i] and static.tabs[i].name or ("Tree " .. i) end
  local liveOf, taken, spells, placed = {}, {}, {}, {}   -- static id -> game id; "spec:row:col" -> game id; spell -> game id
  local function put(n, sp, row, col, st)
    local spell = n.spell or (st and st.spell) or 0
    local icon = (n.spell and C.SpellIcon(n.spell)) or (st and st.icon) or 0
    d.nodes[n.id] = { n.entry or (st and st.entry) or 0, n.max, spell, sp, row, col, n.name, icon or 0 }
    taken[sp .. ":" .. row .. ":" .. col] = n.id
    if spell ~= 0 then spells[spell] = n.id end
    placed[n.id] = n
  end
  for _, n in ipairs(nodes) do
    local st = staticOf[n.id]
    if st then put(n, st.tab, st.tier + 1, st.col + 1, st) liveOf[st.id] = n.id end
  end
  local leftOut = {}
  local new = {}
  for _, n in ipairs(nodes) do
    if not staticOf[n.id] then
      local row = settle(n.posY, rowY, stepY, 9)
      local sp, col
      for s = 1, 3 do
        local c = settle(n.posX, colX[s], stepX, 4)
        if c then if sp then sp = false else sp, col = s, c end end
      end
      local why = (not (row and sp)) and "off the grid" or (n.spell and spells[n.spell] and "a copy of a talent on the grid")
        or (taken[sp .. ":" .. row .. ":" .. col] and "on a square already taken") or nil
      if why then
        leftOut[#leftOut + 1] = ("%d %s at (%s, %s): %s"):format(n.id, n.name, tostring(n.posX), tostring(n.posY), why)
      else
        put(n, sp, row, col, nil)
        new[#new + 1] = n
      end
    end
  end
  -- gates, groups and arrows: the static tree's, on the game's ids; a new node takes those of its spec and row's static nodes
  for g, list in pairs(static.groups) do
    local out = {}
    for _, sid in ipairs(list) do if liveOf[sid] then out[#out + 1] = liveOf[sid] end end
    d.groups[g] = out
  end
  for sid, lid in pairs(liveOf) do
    local gs = static.byId[sid].gates
    if gs and #gs > 0 then
      d.gates[lid] = {}
      for i, g in ipairs(gs) do d.gates[lid][i] = { g[1], g[2] } end
    end
  end
  for _, n in ipairs(new) do
    local me = d.nodes[n.id]
    local mate
    for _, st in pairs(static.byId) do
      if st.tab == me[4] and st.tier + 1 == me[5] and liveOf[st.id] and (not mate or st.id < mate.id) then mate = st end
    end
    if mate then
      local gs = d.gates[liveOf[mate.id]]
      if gs then d.gates[n.id] = {} for i, g in ipairs(gs) do d.gates[n.id][i] = { g[1], g[2] } end end
      for g, list in pairs(static.groups) do
        for _, sid in ipairs(list) do
          if sid == mate.id then table.insert(d.groups[g], n.id) table.sort(d.groups[g]) break end
        end
      end
    end
  end
  for _, e in ipairs(static.data.edges) do
    if liveOf[e[1]] and liveOf[e[2]] then d.edges[#d.edges + 1] = { liveOf[e[1]], liveOf[e[2]] } end
  end
  local isNew = {}
  for _, n in ipairs(new) do isNew[n.id] = true end
  for _, n in pairs(placed) do
    for _, t in ipairs(n.edges or {}) do
      if placed[t] and (isNew[n.id] or isNew[t]) then d.edges[#d.edges + 1] = { n.id, t } end
    end
  end
  local T = buildForever(d)
  T.live, T.leftOut = true, leftOut
  return T
end

-- Reads the game's tree for the player's class (on login, when the world is entered, when the talents' config changes, and when the
-- Talents tab opens) and, the first time it can, uses it instead of the static tree. Returns true when the tree changed.
function ST:RefreshLiveTree(force)
  if not (C.IsForever and C.IsForever()) then return false end
  local cls = self:ClassFile()
  if not cls then return false end
  local cur = self.trees[cls]
  if cur and cur.live then return false end
  local config = C.TalentConfig and C.TalentConfig()
  if not config then return false end
  -- (one try per config, unless the game says the config changed: a failed read is not repeated on every redraw)
  if not force and self.liveTriedFor == config then return false end
  self.liveTriedFor = config
  local ok, LT, why = pcall(self.LiveTree, self, cls)
  if not ok then Panoply:Debug("spec", "live tree", tostring(LT)) return false end
  if not LT then self.liveWhyNot = why return false end
  self.trees[cls] = LT
  if self.ready then self.ready[cls] = nil end
  if self.liveMaps then self.liveMaps[cls] = nil end
  self.edit = nil
  Panoply:Fire("SPEC_PLAN_CHANGED", nil)
  return true
end
for _, ev in ipairs({ "PLAYER_ENTERING_WORLD", "TRAIT_CONFIG_UPDATED" }) do ST:On(ev, function() ST:RefreshLiveTree(true) end) end

-- A level-60 layout { [talent id] = rank } laid as points in an order the rules allow (each point the first legal one, top of the tree
-- first). The rules only ever open more as points are added, so this finds an order whenever one exists. Returns points, or nil and why.
function ST:LayoutOrder(classFile, want)
  local T = self:Trees(classFile)
  local list, total = {}, 0
  for id, r in pairs(want) do
    local tal = T.byId[id]
    if not tal then return nil, ("talent %s is not in the tree"):format(tostring(id)) end
    if r > tal.ranks then return nil, ("%s at %d of %d ranks"):format(tal.name, r, tal.ranks) end
    list[#list + 1] = tal
    total = total + r
  end
  table.sort(list, function(a, b)
    if a.tab ~= b.tab then return a.tab < b.tab end
    if a.tier ~= b.tier then return a.tier < b.tier end
    return a.col < b.col
  end)
  local ranks, spent, pts = {}, { 0, 0, 0 }, {}
  for _ = 1, total do
    local pick
    for _, tal in ipairs(list) do
      if (ranks[tal.id] or 0) < want[tal.id] and self:CanAdd(T, ranks, spent, tal) then pick = tal break end
    end
    if not pick then
      local _, err
      for _, tal in ipairs(list) do if (ranks[tal.id] or 0) < want[tal.id] then _, err = self:CanAdd(T, ranks, spent, tal) break end end
      return nil, err or "no order fits the rules"
    end
    pts[#pts + 1] = pick.id
    ranks[pick.id] = (ranks[pick.id] or 0) + 1
    spent[pick.tab] = spent[pick.tab] + 1
  end
  return pts
end

-- The rank a prerequisite needs before the talent it points to opens: Classic Era, the talent's own prerequisite rank; WoW Forever,
-- the class's rule in the data (prereq "started": one point; "full": all of its ranks, as the generated data says for every class).
function ST:NeedRank(T, pre, tal)
  if T and T.forever then return (T.prereq == "started") and 1 or (pre and pre.ranks or 1) end
  return tal and tal.prereqRank or (pre and pre.ranks) or 1
end

-- Points a talent's gate counts: the ranks in its group (WoW Forever)
local function groupPoints(T, g, ranks)
  local s = 0
  for _, id in ipairs(T.groups[g] or {}) do s = s + (ranks[id] or 0) end
  return s
end
ST.GroupPoints = groupPoints

-- The most points a talent's gates ask for (the "Requires N points" line): WoW Forever, its largest gate; Classic Era, 5 a row
function ST:GatePoints(T, tal)
  if T and T.forever then
    local most = 0
    for _, g in ipairs(tal.gates or {}) do if g[2] > most then most = g[2] end end
    return most
  end
  return tal.tier * 5
end

function ST:Trees(classFile)
  classFile = classFile or self:ClassFile()
  if self.trees[classFile] then return self.trees[classFile] end
  local forever = C.IsForever and C.IsForever()
  if forever then
    local T = foreverTrees(classFile)
    self.trees[classFile] = T
    return T
  end
  local raw = Panoply.TalentData and Panoply.TalentData.classes[classFile]
  if not raw then return nil end
  local T = { tabs = {}, byId = {}, byName = {}, rows = ST.GRID_ROWS }
  for ti, tab in ipairs(raw) do
    local t = { index = ti, id = tab.id, name = tab.name, talents = {} }
    for li, r in ipairs(tab.talents) do
      local tal = { id = r[1], tier = r[2], col = r[3], key = r[4], name = (forever and r[10]) or r[4], ranks = r[5],
                    prereq = r[6] ~= 0 and r[6] or nil, prereqRank = r[7], spell = r[8], icon = r[9], tab = ti, letter = li }
      t.talents[li] = tal
      T.byId[tal.id] = tal
      T.byName[ti .. ":" .. r[4]] = tal
    end
    T.tabs[ti] = t
  end
  -- Forever names as a second way in, never over an Era name (Forever reuses some Era names)
  for ti, t in ipairs(T.tabs) do
    for li, tal in ipairs(t.talents) do
      local fn = raw[ti].talents[li][10]
      if fn and not T.byName[ti .. ":" .. fn] then T.byName[ti .. ":" .. fn] = tal end
    end
  end
  self.trees[classFile] = T
  return T
end

-- WoW Forever: the player's class tree as the game has it now, read with the trait API (Compat): { [node id] = node }, the config;
-- nil when the game cannot be asked (no config yet, another class, no talent data). Classic Era's talent functions are never called.
function ST:LiveNodes(classFile)
  classFile = classFile or self:ClassFile()
  local T = self:Trees(classFile)
  if not (T and T.forever) or classFile ~= self:ClassFile() then return nil end
  local config = C.TalentConfig and C.TalentConfig()
  if not config then return nil end
  local function read()
    local map, cached = self:LiveMap(classFile, config)
    local nodes, any, miss = {}, false, false
    for id, lid in pairs(map) do
      local n = C.TalentNode(config, lid)
      if n then n.liveId = lid; nodes[id] = n; any = true else miss = true end
    end
    return nodes, any, miss and cached
  end
  local nodes, any, stale = read()
  -- a node the kept map points at is gone (a new client build renumbered it): the map is made again once
  if stale then self.liveMaps[classFile] = nil; nodes, any = read() end
  if not any then return nil end
  return nodes, config
end

-- Our node id -> the game's node id (0.9.9.4 review: a node whose id moved is found again by its spell id
-- and rank count, else by its name and rank count when the game gives no spell; a node that matches nothing is left out). Made once per
-- class and config and kept; returns the map and whether it was the kept one. When the game cannot list its tree, our ids as they are.
function ST:LiveMap(classFile, config)
  self.liveMaps = self.liveMaps or {}
  local kept = self.liveMaps[classFile]
  if kept and kept.config == config then return kept.map, true end
  local T = self:Trees(classFile)
  local map = {}
  local ids = C.TalentTreeNodes and C.TalentTreeNodes(T.tree)
  if not ids or #ids == 0 then
    for id in pairs(T.byId) do map[id] = id end
  else
    local live, bySpell, byName = {}, {}, {}
    local function index(t, k, lid) if t[k] == nil then t[k] = lid else t[k] = false end end   -- false: two nodes share it
    for _, lid in ipairs(ids) do
      local n = C.TalentNode(config, lid)
      if n then
        n.spell, n.name = C.TalentEntrySpell(config, n.entry)
        live[lid] = n
        if n.spell then index(bySpell, n.spell .. "#" .. n.max, lid) end
        if n.name then index(byName, n.name .. "#" .. n.max, lid) end
      end
    end
    for id, tal in pairs(T.byId) do
      local l, hit = live[id], nil
      if l and l.max == tal.ranks and ((l.spell and tal.spell and l.spell == tal.spell) or (not (l.spell and tal.spell) and (not l.name or l.name == tal.name))) then
        hit = id
      else
        hit = tal.spell and bySpell[tal.spell .. "#" .. tal.ranks] or nil
        if not hit then
          local h = byName[tal.name .. "#" .. tal.ranks]
          if h and not (live[h].spell and tal.spell) then hit = h end
        end
      end
      if hit then map[id] = hit end
    end
  end
  self.liveMaps[classFile] = { config = config, map = map }
  return map, false
end

-- The game's own view of a talent (name, icon, rank) when the talent API is there; matched by tree,
-- row and column, so a renamed talent still lines up. WoW Forever: the node, by its id, through the trait API.
function ST:LiveTalent(tal)
  if C.IsForever and C.IsForever() then
    local T = self:Trees()
    if not (T and T.byId[tal.id] == tal) then return nil end
    local config = C.TalentConfig and C.TalentConfig()
    local lid = config and self:LiveMap(self:ClassFile(), config)[tal.id]
    local n = lid and C.TalentNode(config, lid)
    if not n then return nil end
    local spell, name = C.TalentEntrySpell(config, n.entry)
    return { name = name or tal.name, icon = C.SpellIcon(spell or tal.spell), rank = n.rank, ranks = n.max ~= 0 and n.max or nil, spell = spell }
  end
  if not (_G.GetNumTalents and _G.GetTalentInfo) then return nil end
  local n = GetNumTalents(tal.tab) or 0
  for i = 1, n do
    local name, icon, tier, col, rank, maxRank = GetTalentInfo(tal.tab, i)
    if tier == tal.tier + 1 and col == tal.col + 1 then
      return { index = i, name = name, icon = icon, rank = rank or 0, ranks = maxRank }
    end
  end
  return nil
end

-- Current ranks from the game: { [talent id] = rank }, plus points per tree. nil without the API.
function ST:LiveRanks(classFile)
  local T = self:Trees(classFile)
  if T and T.forever then
    local nodes = self:LiveNodes(classFile)
    if not nodes then return nil end
    local ranks, spent = {}, { 0, 0, 0 }
    for id, n in pairs(nodes) do
      local tal = T.byId[id]
      if tal and n.rank > 0 then ranks[id] = n.rank; spent[tal.tab] = spent[tal.tab] + n.rank end
    end
    return ranks, spent
  end
  if C.IsForever and C.IsForever() then return nil end
  if not T or not (_G.GetNumTalentTabs and _G.GetTalentInfo) then return nil end
  local ranks, spent = {}, { 0, 0, 0 }
  for ti, tab in ipairs(T.tabs) do
    local pos = {}
    for _, tal in ipairs(tab.talents) do pos[tal.tier .. ":" .. tal.col] = tal end
    for i = 1, (GetNumTalents(ti) or 0) do
      local _, _, tier, col, rank = GetTalentInfo(ti, i)
      local tal = tier and pos[(tier - 1) .. ":" .. ((col or 1) - 1)]
      if tal and (rank or 0) > 0 then ranks[tal.id] = rank; spent[ti] = spent[ti] + rank end
    end
  end
  return ranks, spent
end

-- Does the game's talent data still match ours? (names may differ; rows, columns and ranks must not)
function ST:DataMatchesGame(classFile)
  local T = self:Trees(classFile)
  if T and T.forever then
    -- WoW Forever: every node of our tree is in the game's, with the same ranks (true when the game cannot be asked)
    local nodes = self:LiveNodes(classFile)
    if not nodes then return true end
    for id, tal in pairs(T.byId) do
      local n = nodes[id]
      if not n or (n.max ~= 0 and n.max ~= tal.ranks) then return false end
    end
    return true
  end
  if C.IsForever and C.IsForever() then return true end
  if not T or not (_G.GetNumTalentTabs and _G.GetTalentInfo) then return true end
  if (GetNumTalentTabs() or 0) ~= #T.tabs then return false end
  for ti, tab in ipairs(T.tabs) do
    if (GetNumTalents(ti) or 0) ~= #tab.talents then return false end
    for _, tal in ipairs(tab.talents) do
      local live = self:LiveTalent(tal)
      if not live or (live.ranks and live.ranks ~= tal.ranks) then return false end
    end
  end
  return true
end

-------------------------------------------------------------------------------
-- The rules checker (SPEC 22.3.2): row t (0-based) needs 5*t points in that tree first, the
-- prerequisite talent needs its points, and no talent goes past its ranks. 51 points at most.
-- points = { talent id, ... } one per level from 10. Returns true, or nil + a plain message
-- + the index of the first bad point.
-------------------------------------------------------------------------------
function ST:CanAdd(T, ranks, spent, tal)
  local tab = T.tabs[tal.tab]
  if (ranks[tal.id] or 0) >= tal.ranks then
    return nil, ("%s already has all %d points."):format(tal.name, tal.ranks)
  end
  if T.forever then
    -- WoW Forever: each gate counts the points in its own group of talents (the ones above it), and of several arrows into a
    -- talent any one opens it (the trait tree's rules)
    for _, g in ipairs(tal.gates) do
      local have = groupPoints(T, g[1], ranks)
      if have < g[2] then
        return nil, ("%s needs %d points in %s first (%d so far)."):format(tal.name, g[2], tab.name, have)
      end
    end
    if #tal.prereqs > 0 then
      local names = {}
      for _, pid in ipairs(tal.prereqs) do
        local pre = T.byId[pid]
        local need = self:NeedRank(T, pre, tal)
        if (ranks[pid] or 0) >= need then return true end
        names[#names + 1] = ("%s %d/%d"):format(pre.name, need, pre.ranks)
      end
      return nil, ("%s needs %s first."):format(tal.name, table.concat(names, " or "))
    end
    return true
  end
  if spent[tal.tab] < tal.tier * 5 then
    return nil, ("%s needs %d points in %s first."):format(tal.name, tal.tier * 5, tab.name)
  end
  if tal.prereq then
    local pre = T.byId[tal.prereq]
    if (ranks[tal.prereq] or 0) < tal.prereqRank then
      return nil, ("%s needs %s %d/%d first."):format(tal.name, pre and pre.name or "another talent", tal.prereqRank, pre and pre.ranks or tal.prereqRank)
    end
  end
  return true
end

function ST:Check(classFile, points)
  local T = self:Trees(classFile)
  if not T then return nil, "No talent data for this class.", 1 end
  if #points > self.POINTS then return nil, ("A plan has at most %d points (levels 10 to 60)."):format(self.POINTS), self.POINTS + 1 end
  local ranks, spent = {}, { 0, 0, 0 }
  for i, id in ipairs(points) do
    local tal = T.byId[id]
    if not tal then return nil, "A talent in this plan is not in the game's talent data.", i end
    local ok, err = self:CanAdd(T, ranks, spent, tal)
    if not ok then return nil, err, i end
    ranks[id] = (ranks[id] or 0) + 1
    spent[tal.tab] = spent[tal.tab] + 1
  end
  return true
end

-- Ranks and points per tree after the first n points of a plan.
function ST:RanksAt(classFile, points, n)
  local T = self:Trees(classFile)
  local ranks, spent = {}, { 0, 0, 0 }
  for i = 1, math.min(n or #points, #points) do
    local tal = T.byId[points[i]]
    if tal then ranks[tal.id] = (ranks[tal.id] or 0) + 1; spent[tal.tab] = spent[tal.tab] + 1 end
  end
  return ranks, spent
end

-- Ready-made steps { tree, talent name, n } to talent ids. The steps are a priority list: the
-- order is fitted to the rules by code (each level takes the first listed point that is legal
-- then), so a write-up never has to count row gates by hand. Returns points, or nil and why.
function ST:Expand(classFile, steps)
  local T = self:Trees(classFile)
  if not T then return nil, "No talent data for " .. tostring(classFile) end
  local want, total = {}, 0
  for _, s in ipairs(steps) do
    local tal = T.byName[s[1] .. ":" .. s[2]]
    if not tal then return nil, ("No talent %q in tree %d."):format(s[2], s[1]) end
    for _ = 1, s[3] do want[#want + 1] = tal end
    total = total + s[3]
  end
  if total ~= self.POINTS then return nil, ("%d points; a full plan has %d."):format(total, self.POINTS) end
  local count = {}
  for _, tal in ipairs(want) do
    count[tal.id] = (count[tal.id] or 0) + 1
    if count[tal.id] > tal.ranks then return nil, ("%s is listed for %d points; it has %d."):format(tal.name, count[tal.id], tal.ranks) end
  end
  local points, used, ranks, spent = {}, {}, {}, { 0, 0, 0 }
  for lv = 1, total do
    local pick, firstErr
    for i, tal in ipairs(want) do
      if not used[i] then
        local ok, err = self:CanAdd(T, ranks, spent, tal)
        if ok then pick = i break end
        firstErr = firstErr or err
      end
    end
    if not pick then return nil, ("level %d: %s"):format(self.FIRST_LEVEL + lv - 1, firstErr) end
    used[pick] = true
    local tal = want[pick]
    points[lv] = tal.id
    ranks[tal.id] = (ranks[tal.id] or 0) + 1
    spent[tal.tab] = spent[tal.tab] + 1
  end
  return points
end

