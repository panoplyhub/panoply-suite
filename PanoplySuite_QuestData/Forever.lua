-- PanoplySuite_QuestData: WoW Forever overlay (loaded by the Forever/Camelot TOCs and the fallback TOC).
-- Hand-written, no generated server data. Distributed under the GNU GPL v3 with the rest of the add-on.
--
-- WoW Forever runs the same classic world as Era, but the client re-drew some zone maps and added
-- races and zones. What is known (from the Forever client's own DB2 tables, build 1.60.1.70707):
--   * Zone rectangles differ for Mulgore (1412), Eastern Plaguelands (1423), Redridge Mountains (1433)
--     and Stormwind City (1453). Data/Zones.lua carries both rectangle sets (DB.foreverRects).
--   * New zone maps: Mount Hyjal (2482), Zephras Isle (2521, 2665), Darkspear Islands (2524),
--     Riverglades (2548), Shen'dralas (2652). The server database has NO NPCs, objects or quests there.
--   * New races: High Order Skyborne (raceID 95, Alliance, race bit 32) and Windshaper Skyborne
--     (raceID 96, Horde, race bit 33).
-- What is NOT known and is flagged instead of guessed:
--   * whether NPCs inside the re-drawn zones still stand where the 1.12 server puts them
--     (spots there are marked unverified until a player sees the NPC; the adapter learns positions);
--   * Forever-only quest NPCs, objectives, access rules and positions (verified titles are below);
--   * whether quests open to "all Alliance" / "all Horde" races also admit the Skyborne (assumed yes).
